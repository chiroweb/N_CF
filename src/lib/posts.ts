export function getPost(id: number | string): Post | undefined {
  const numId = typeof id === "string" ? parseInt(id, 10) : id;
  if (!Number.isFinite(numId)) return undefined;
  return POSTS.find((p) => p.id === numId);
}

export function listPostIds(): string[] {
  return POSTS.map((p) => String(p.id));
}
